"""Generate bl_cp864ar.h: the Arabic (UAE) Braille Lite 2000's letters (bl2_ar_ae_1998_12, bl_languages.txt's text
864ar) for bl_voice.c's BLV_CP864AR -- bytes 0x80-0xFF of DOS code page 864 as Python's codec decodes them, the 27 of
them the unit speaks, and every form of a letter it speaks folded onto it.

Read from the unit (every byte 80h-FFh sent between two x's through the voice, its phonemes logged, 2026-10-16): it
speaks exactly 27 bytes, each a CP864 Arabic letter in its isolated or initial form (SPOKEN below), and nothing for
the other high bytes (the medial and final forms, the other letters, the symbols).  The unit reads one form per letter,
so the letter's position in a word does not matter: a base letter (U+0621-U+064A) and every presentation form of it
(U+FE80-U+FEFC, by Unicode's own decomposition) are sent as the spoken form, and so are a letter's other forms (a
hamza's seat, a madda, wasla: FOLDS).  A letter the unit has no byte for (alef maksura, teh marbuta, zah) is never sent
as another letter: it stays the gap the firmware has (Tomi).  Arabic-Indic digits go to ASCII digits (the unit reads
its numbers itself, half in Arabic).  The vowel marks, the tatweel and a bare hamza are dropped by bl_voice.c's
clean (a space would split the word), not here.

    python gen_cp864ar.py           # rewrite the header
    python gen_cp864ar.py --check   # exit 1 if it is stale (run_tests)
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "bl_cp864ar.h")

# the bytes the unit speaks (sweep, 2026-10-16) and what it said for each
SPOKEN = {0xA9: "B", 0xAA: "T", 0xAB: "T", 0xAD: "J", 0xAE: "OU HF", 0xAF: "K", 0xC7: "AE", 0xCF: "D", 0xD0: "D",
          0xD1: "R1", 0xD2: "Z", 0xD3: "S", 0xD4: "SCH", 0xD5: "S S", 0xD6: "D D", 0xD7: "T T", 0xDF: "K HVC",
          0xE1: "F", 0xE2: "K", 0xE8: "W", 0xEE: "T SCH", 0xEF: "M", 0xF2: "N", 0xF3: "OU HF", 0xFB: "L", 0xFC: "K",
          0xFD: "Y1"}
# letters with no byte of their own, and the letter whose byte is sent (conservative; each by its sound)
FOLDS = {
    0x0622: 0x0627,   # alef with madda above -> alef
    0x0623: 0x0627,   # alef with hamza above -> alef
    0x0625: 0x0627,   # alef with hamza below -> alef
    0x0671: 0x0627,   # alef wasla -> alef
    0x0624: 0x0648,   # waw with hamza above -> waw
    0x0626: 0x064A,   # yeh with hamza above -> yeh
    # Only forms of a letter fold onto it (a hamza's seat, a madda, wasla, the positional forms), as an accented
    # letter goes out as its base letter for the other units.  A letter the firmware has no byte for is NOT sent as
    # another letter: alef maksura, teh marbuta and zah stay the gaps the unit has (Tomi, 2026-10-16: "any gaps
    # unfortunately we should keep as they were, at least for now").
}


def base_of(cp):
    """the letter a presentation form is a form of (Unicode's decomposition: "<isolated> 0628"), or None"""
    d = unicodedata.decomposition(chr(cp)).split()
    if len(d) == 2 and d[0].startswith("<"):
        return int(d[1], 16)
    return None


def tables():
    high = [ord(bytes([b]).decode("cp864", errors="replace")) for b in range(0x80, 0x100)]
    high = [0 if c == 0xFFFD else c for c in high]
    spoken = {}
    for b in sorted(SPOKEN):
        cp = high[b - 0x80]
        assert high.index(cp) == b - 0x80, "byte %02X: its code point appears earlier in the page" % b
        letter = base_of(cp) or cp
        assert 0x0621 <= letter <= 0x064A, "byte %02X is not an Arabic letter (%04X)" % (b, cp)
        assert letter not in spoken, "two spoken bytes for %04X" % letter
        spoken[letter] = cp
    folds = {}
    letters = list(range(0x0621, 0x064B)) + [0x0671]
    for L in letters:
        target = spoken.get(L) or spoken.get(FOLDS.get(L, -1))
        if target and target != L:
            folds[L] = target
    for cp in range(0xFE80, 0xFEFD):                 # the presentation forms of single letters
        L = base_of(cp)
        if L is None:
            continue
        target = spoken.get(L) or spoken.get(FOLDS.get(L, -1))
        if target and target != cp:
            folds[cp] = target
    for d in range(10):                              # Arabic-Indic and Eastern Arabic-Indic digits -> ASCII
        folds[0x0660 + d] = 0x30 + d
        folds[0x06F0 + d] = 0x30 + d
    return high, sorted(spoken.values()), sorted(folds.items())


def render():
    high, keep, folds = tables()
    lines = ["/* Generated by gen_cp864ar.py from Python's cp864 codec, Unicode's decompositions and the Arabic (UAE)",
             "   unit's 27 spoken letters: do not edit. */",
             "#ifndef BL_CP864AR_H", "#define BL_CP864AR_H", "",
             "/* the code point of each byte 0x80 + i (code page 864) */",
             "static const unsigned short bl_cp864_high[128] = {"]
    for i in range(0, 128, 8):
        lines.append("    " + " ".join("0x%04X," % c for c in high[i:i + 8]))
    lines += ["};", "", "/* the 27 letters the unit speaks (their isolated or initial forms) */",
              "static const unsigned short keep_864ar[] = {"]
    for i in range(0, len(keep), 9):
        lines.append("    " + " ".join("0x%04X," % c for c in keep[i:i + 9]))
    lines += ["};", "", "/* every Arabic letter and form -> the form the unit speaks; digits -> ASCII */",
              "static const unsigned short fold_864ar[][2] = {"]
    for i in range(0, len(folds), 6):
        lines.append("    " + " ".join("{0x%04X, 0x%04X}," % f for f in folds[i:i + 6]))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if old != text:
            print("bl_cp864ar.h is stale: run gen_cp864ar.py")
            return 1
        print("bl_cp864ar.h matches")
        return 0
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
